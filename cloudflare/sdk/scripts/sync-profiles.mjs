// Regenerates src/profiles/fonts.generated.ts from spec/fonts.json when that file exists,
// otherwise from test/fixtures/profile.sample.json (so the package builds before the real
// profiles are published). Run via `npm run sync-profiles` or as part of `npm run build`.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const spec = resolve(here, "../../../spec/fonts.json");
const sample = resolve(here, "../test/fixtures/profile.sample.json");
const out = resolve(here, "../src/profiles/fonts.generated.ts");
const iconsSpec = resolve(here, "../../../spec/icons.json");
const iconsOut = resolve(here, "../src/profiles/icons.generated.ts");

const source = existsSync(spec) ? spec : sample;
const json = JSON.parse(readFileSync(source, "utf8"));
if (!json || typeof json !== "object" || typeof json.profiles !== "object") {
  throw new Error(`${source}: expected { spec_version, profiles }`);
}
const banner =
  `// GENERATED by scripts/sync-profiles.mjs from ${existsSync(spec) ? "spec/fonts.json" : "test/fixtures/profile.sample.json (spec/fonts.json not found)"}.\n` +
  `// Do not edit by hand; run \`npm run sync-profiles\` in cloudflare/sdk.\n`;
mkdirSync(dirname(out), { recursive: true });
const body = `${banner}const fonts = ${JSON.stringify(json, null, 2)} as const;\nexport default fonts;\nexport const FONTS_SOURCE = ${JSON.stringify(existsSync(spec) ? "spec" : "sample")};\n`;
let existing = null;
try { existing = readFileSync(out, "utf8"); } catch {}
if (existing !== body) {
  writeFileSync(out, body);
  console.log(`sync-profiles: wrote ${out} from ${source}`);
}

// The icon names a firmware build actually compiles. Apps are validated against this list, so a
// name the device cannot draw is caught in `wrangler dev` rather than silently drawing nothing.
if (existsSync(iconsSpec)) {
  const doc = JSON.parse(readFileSync(iconsSpec, "utf8"));
  const names = Array.isArray(doc) ? doc : (doc.icons ?? []);
  if (!Array.isArray(names) || names.some((n) => typeof n !== "string")) {
    throw new Error(`${iconsSpec}: expected { icons: string[] }`);
  }
  const iconBody =
    `// GENERATED by scripts/sync-profiles.mjs from spec/icons.json.\n` +
    `// Do not edit by hand; run \`npm run sync-profiles\` in cloudflare/sdk.\n` +
    `export const ICON_NAMES: readonly string[] = ${JSON.stringify([...names].sort(), null, 0)};\n`;
  let had = null;
  try { had = readFileSync(iconsOut, "utf8"); } catch {}
  if (had !== iconBody) {
    writeFileSync(iconsOut, iconBody);
    console.log(`sync-profiles: wrote ${iconsOut} (${names.length} icons)`);
  }
}
